/**
 * Writes admin.credentials.ts (password hash) and admin.publish.ts (GitHub token).
 *
 * Local: .env → ADMIN_PASSWORD, ADMIN_GITHUB_TOKEN
 * CI: GitHub Actions / Environment secrets with the same names
 */
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, '..');
const envPath = path.join(root, '.env');
const credentialsPath = path.join(
  root,
  'src',
  'app',
  'admin',
  'admin.credentials.ts'
);
const publishPath = path.join(root, 'src', 'app', 'admin', 'admin.publish.ts');

function loadDotEnv() {
  if (!fs.existsSync(envPath)) return;
  const text = fs.readFileSync(envPath, 'utf8');
  for (const line of text.split(/\r?\n/)) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith('#')) continue;
    const eq = trimmed.indexOf('=');
    if (eq < 1) continue;
    const key = trimmed.slice(0, eq).trim();
    let value = trimmed.slice(eq + 1).trim();
    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    }
    if (!(key in process.env)) process.env[key] = value;
  }
}

function escapeTsSingleQuoted(value) {
  return value.replace(/\\/g, '\\\\').replace(/'/g, "\\'");
}

loadDotEnv();

const password = process.env.ADMIN_PASSWORD?.trim() || '';
const githubToken = process.env.ADMIN_GITHUB_TOKEN?.trim() || '';
const githubOwner =
  process.env.ADMIN_GITHUB_OWNER?.trim() ||
  process.env.GITHUB_REPOSITORY_OWNER?.trim() ||
  'Emmanuel-Ratemo';
const githubRepo =
  process.env.ADMIN_GITHUB_REPO?.trim() ||
  process.env.GITHUB_REPOSITORY?.trim()?.split('/')[1] ||
  'bakery';
const requirePassword = process.argv.includes('--require');

if (!password) {
  const message =
    'ADMIN_PASSWORD is empty. Set it in .env locally or as a GitHub Actions secret.';
  if (requirePassword) {
    console.error(message);
    process.exit(1);
  }
  console.warn(`Warning: ${message}`);
  console.warn('Admin login will fail until a password is configured.');
}

const hash = password
  ? crypto.createHash('sha256').update(password, 'utf8').digest('hex')
  : '';

fs.writeFileSync(
  credentialsPath,
  `/**
 * Generated by scripts/generate-admin-credentials.mjs — do not edit by hand.
 * Source: ADMIN_PASSWORD from .env (local) or GitHub Actions secret (CI).
 */
export const ADMIN_PASSWORD_HASH = '${hash}';
`,
  'utf8'
);

fs.writeFileSync(
  publishPath,
  `/**
 * Generated by scripts/generate-admin-credentials.mjs — do not edit by hand.
 * Source: ADMIN_GITHUB_TOKEN from .env (local) or GitHub Environment/Actions secret (CI).
 *
 * Note: a write token in a static site can be extracted from the built JS.
 * Use a fine-grained token limited to Contents write on this repo only.
 */
export const ADMIN_GITHUB_TOKEN = '${escapeTsSingleQuoted(githubToken)}';
export const ADMIN_GITHUB_OWNER = '${escapeTsSingleQuoted(githubOwner)}';
export const ADMIN_GITHUB_REPO = '${escapeTsSingleQuoted(githubRepo)}';
`,
  'utf8'
);

console.log(
  hash
    ? `Wrote admin credentials hash to ${path.relative(root, credentialsPath)}`
    : `Wrote empty admin credentials hash to ${path.relative(root, credentialsPath)}`
);
console.log(
  githubToken
    ? `Wrote GitHub publish token to ${path.relative(root, publishPath)}`
    : `Wrote empty GitHub publish token to ${path.relative(root, publishPath)} (live Admin uploads stay browser-only)`
);
