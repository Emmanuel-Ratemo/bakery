/**
 * Writes src/app/admin/admin.credentials.ts from ADMIN_PASSWORD.
 *
 * Local: put ADMIN_PASSWORD in .env (gitignored)
 * CI: set env from GitHub Actions secret ADMIN_PASSWORD
 */
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, '..');
const envPath = path.join(root, '.env');
const outPath = path.join(root, 'src', 'app', 'admin', 'admin.credentials.ts');

function loadDotEnv() {
  if (!fs.existsSync(envPath)) return;
  const text = fs.readFileSync(envPath, 'utf8');
  for (const line of text.split(/\r?\n/)) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith('#')) continue;
    const eq = trimmed.indexOf('=');
    if (eq < 1) continue;
    const key = trimmed.slice(0, eq).trim();
    let value = trimmed.slice(eq + 1).trim();
    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    }
    if (!(key in process.env)) process.env[key] = value;
  }
}

loadDotEnv();

const password = process.env.ADMIN_PASSWORD?.trim() || '';
const requirePassword = process.argv.includes('--require');

if (!password) {
  const message =
    'ADMIN_PASSWORD is empty. Set it in .env locally or as a GitHub Actions secret.';
  if (requirePassword) {
    console.error(message);
    process.exit(1);
  }
  console.warn(`Warning: ${message}`);
  console.warn('Admin login will fail until a password is configured.');
}

const hash = password
  ? crypto.createHash('sha256').update(password, 'utf8').digest('hex')
  : '';

const contents = `/**
 * Generated by scripts/generate-admin-credentials.mjs — do not edit by hand.
 * Source: ADMIN_PASSWORD from .env (local) or GitHub Actions secret (CI).
 */
export const ADMIN_PASSWORD_HASH = '${hash}';
`;

fs.writeFileSync(outPath, contents, 'utf8');
console.log(
  hash
    ? `Wrote admin credentials hash to ${path.relative(root, outPath)}`
    : `Wrote empty admin credentials hash to ${path.relative(root, outPath)}`
);
